export type UiLang = "zh" | "en";

export const DICTIONARIES: Record<UiLang, Record<MessageKey, string>> = {
  zh,
  en,
};

export function format(
  template: string,
  vars?: Record<string, string | number | undefined>,
) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    vars[key] === undefined ? match : String(vars[key]),
  );
}

/** Pick the UI language from a cookie value or an Accept-Language header. */
export function resolveUiLang(
  cookie: string | undefined,
  acceptLanguage: string | null,
): UiLang {
  if (cookie === "zh" || cookie === "en") return cookie;
  const first = acceptLanguage?.split(",")[0]?.trim().toLowerCase() ?? "";
  return !first || first.startsWith("zh") ? "zh" : "en";
}
